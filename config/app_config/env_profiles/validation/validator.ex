defmodule ProCoder.Config.Validator do
  @moduledoc """
  The Configuration Validation Engine (CVE) for ProCoder.
  
  This module acts as the gatekeeper for system startup, ensuring all environment
  configurations adhere to required schemas and invariants before the application
  transitions into an active state. It utilizes the ProCoder.Config.Schema DSL.
  """

  require Logger

  @doc """
  Performs a high-level validation check across the system configuration.
  
  Should be invoked during the application boot process (e.g., in Application.start/2).
  If validation fails, this function will raise an exception, causing the 
  BEAM VM to halt immediately (Fail-Fast).
  """
  def validate_environment! do
    # Fetch current app config
    config = Application.get_all_env(:procoder)
    
    # 1. Schema Validation
    # We aggregate schemas from relevant modules to enforce constraints
    # (e.g., SessionManager, Brain.Client, Repo)
    validate_core_services!(config)
    
    # 2. Invariant Validation (Filesystem/Connectivity)
    validate_system_invariants!(config)
    
    :ok
  end

  defp validate_core_services!(config) do
    # Example enforcement: Check if mandatory services are configured
    # Each service module would define its own schema validation function
    # generated by the ProCoder.Config.Schema DSL.
    
    # Example logic:
    # ProCoder.SessionManager.validate_config!(Map.get(config, ProCoder.SessionManager, %{}))
    
    if is_nil(config[:SessionManager]) do
      raise "CVE: SessionManager configuration missing."
    end
  end

  defp validate_system_invariants!(config) do
    # Check if worktree_root is writable
    worktree = get_in(config, [:SessionManager, :worktree_root])
    if worktree && !File.exists?(worktree) do
      # Attempt directory creation or fail if impossible
      try do
        File.mkdir_p!(worktree)
      rescue
        _ -> raise "CVE: worktree_root '#{worktree}' is not writable or inaccessible."
      end
    end

    # Verify Database connectivity path
    db_path = get_in(config, [:Repo, :database])
    if db_path && db_path != ":memory:" do
      unless File.exists?(Path.dirname(db_path)) do
        raise "CVE: Repository database path '#{Path.dirname(db_path)}' does not exist."
      end
    end
  end

  @doc """
  Safely logs sensitive information by redacting it.
  Use this for any error reporting that might contain keys or secrets.
  """
  def redact(value) when is_binary(value), do: "********"
  def redact(_), do: "********"
end
